/**
 * grading instructions —— 递给判官的评分守则那一段。
 *
 * 单独成一个模块,因为它是 scorer 的身份:CONTEXT.md 写着「改了它就等于换了一个 scorer」
 * (2026-09-18 实测,四档定义表被截断后重判,同一批句子有两句换了档)。
 * `scorer-id.mjs` 拿它算指纹 —— 放在 build-judge-pack.mjs 里算不出来,那个文件是脚本、有顶层副作用。
 */
export function gradingInstructions() {
  const L = [];
  L.push('## 你要判三件事');
  L.push('');
  L.push('### ① 覆盖');
  L.push('');
  L.push('事件清单里每一条,成稿有没有告诉读者这件事?措辞不必相同,说到了就算命中。');
  L.push('清单是从原文独立抽的,不是从成稿抽的。');
  L.push('');
  L.push('**某条下面带「口径分歧」时,成稿写了其中任一个口径都算命中。**');
  L.push('那几个数字/日期在簇内各有独立出处,清单只能锁一个 —— 按锁死的那个判,');
  L.push('等于罚成稿选了另一个同样有据的说法。');
  L.push('');
  L.push('### ② 正确性(四档)');
  L.push('');
  L.push('成稿每一句写得对不对。**证据范围写死:只看该句下面「全簇检索证据」那一组。**');
  L.push('那一组是脚本拿这句话去整簇原文里检索出来的,**与成稿引了谁完全无关** —— 各臂拿到的是同一把尺。');
  L.push('「成稿声称的出处」那一组不参与这一判,它只用来判 ③。');
  L.push('');
  L.push('| 档 | 定义 |');
  L.push('|---|---|');
  L.push('| `fatal` | 改变事件的性质、严重程度或空间/因果关系,读者据此形成完全错误认知 |');
  L.push('| `hard` | 事实错但不改变故事性质,多为日期/主体搬错 |');
  L.push('| `distortion` | 方向对但读者会形成偏差印象 |');
  L.push('| `ok` | 正确的推断、合理省略(**剥掉消息源不算合理省略**,见下)、明示的判断语,都不扣分 |');
  L.push('');
  L.push('**消息源剥离**:原句写「X 说」「据 Y 简介」「据称」,成稿去掉归属、直接当事实陈述。');
  L.push('至少判 `distortion`;若该说法在证据里**被另一方否认、无人证实、或同一消息源自相矛盾**,');
  L.push('读者形成的假信念更强 → 判 `hard`。');
  L.push('这一类**不算「合理省略」** —— 省掉的恰恰是读者判断可信度的依据。');
  L.push('');
  L.push('检索证据里既找不到支持也找不到反证时,先分清是哪一种:');
  L.push('**成稿编的** → 按上表判档;**检索没捞到**(你能看出这件事本簇多半报道过,只是没被检索到)');
  L.push('→ 标 `ok`,并在 `why` 里写「疑似检索缺口」。这两种混在一起会让读数两个方向同时偏。');
  L.push('');
  L.push('### ③ `citedSentenceSuffices` —— 成稿引的那句本身够不够');
  L.push('');
  L.push('**只看「成稿声称的出处」列出的原句。** 这一句(或这几句)自身是否足以支撑成稿这句话的全部成分?');
  L.push('够 → `true`;有成分要靠别处才能补上 → `false`。没有出处的句子记 `false`。');
  L.push('');
  L.push('**③ 与 ② 相互独立**:一句话可以事实全对(② `ok`)但引错了句子(③ `false`),');
  L.push('也可以引对了句子(③ `true`)而写错了(② `hard`)。判完 ③ 不要回头改 ②。');
  L.push('');
  L.push('### 三条守则');
  L.push('');
  L.push('**顺序不能反:先核事实,再读文风。** 你和写作层可能是同一个模型,self-preference 泄漏会让你');
  L.push('觉得自己的输出更顺 —— 先把每个数字、每个主体、每个否定词对着证据比一遍,再谈流畅度。');
  L.push('');
  L.push('**判不准的归属类错误标 `ok` 并说明,不要硬猜。** 主体/日期搬错这类错你召回很低,');
  L.push('宁可漏报,也别造一个假的 `hard`。');
  L.push('');
  L.push('**发现本文件本身有缺陷就说出来**(守则被截断、事件清单重复、证据错配、抓取噪声、检索缺口……),');
  L.push('写进 verdict 的 `packDefects` 数组。历史上 7 个判官里有 6 个报出过真缺陷,这条不是客套。');
  L.push('');
  return L;
}
