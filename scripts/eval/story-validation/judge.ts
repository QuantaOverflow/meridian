import type {
  Story,
  ArticleInfo,
  JudgeResult,
  Verdict,
  RejectedCluster,
  RejectionJudgeResult,
  RejectionVerdict,
} from './types.js';

const AI_WORKER_URL = process.env.AI_WORKER_URL || 'http://localhost:8788';

const JUDGE_PROMPT = (story: Story, articles: ArticleInfo[]) => `
You are a strict editorial judge. Given a story candidate generated by an
upstream news clustering+validation pipeline, decide if it is a REAL coherent
story, a BORDERLINE multi-angle consolidation, or FAKE (LLM padding of
unrelated articles under a common label).

# Definitions
- REAL: articles cover one concrete event/situation. Multi-outlet reporting on
  the same incident or its direct follow-ups.
- BORDERLINE: articles share a tight theme + same actor space (e.g.
  "Trump endorsements in TX and KY" or "World Cup squad announcements PT/BR").
  Defensible as a single editorial unit even if not literally one event.
- FAKE: articles glued together by region/domain label only (e.g.
  "Latin America — protest in Bolivia AND Mexico ex-officials surrender").
  Each item is its own event with no shared narrative.

# Anti-patterns that point to FAKE
- Title joins distinct events with " and ", "; ", "+", or commas
- Title uses only a region/geography/domain word as the unifier
- Same article would naturally appear in two unrelated stories

# Story to judge
Title: ${story.title}
Importance (LLM-assigned): ${story.importance}
Articles (${articles.length}):
${articles.map(a => `- [${a.id}] ${a.title}${a.event_summary_points?.length ? '\n    Points: ' + a.event_summary_points.join('; ') : ''}`).join('\n')}

# Output
Reply with ONLY a JSON object inside a \`\`\`json fenced block. No prose.
{
  "verdict": "REAL" | "BORDERLINE" | "FAKE",
  "coherence": 1-5,
  "title_fit": 1-5,
  "reason": "<one short sentence>"
}
`.trim();

function parseJSON(raw: string): JudgeResult | null {
  const candidates: string[] = [];
  const fenced = raw.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (fenced) candidates.push(fenced[1]);
  const f = raw.indexOf('{');
  const l = raw.lastIndexOf('}');
  if (f >= 0 && l > f) candidates.push(raw.slice(f, l + 1));
  candidates.push(raw);

  for (const c of candidates) {
    const cleaned = c
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .replace(/(^|[^:"'])\/\/[^\n]*/g, '$1')
      .replace(/,(\s*[}\]])/g, '$1')
      .trim();
    try {
      const obj = JSON.parse(cleaned);
      if (obj && typeof obj.verdict === 'string') return obj as JudgeResult;
    } catch {
      /* try next */
    }
  }
  return null;
}

function clamp(n: unknown, lo: number, hi: number): number {
  const v = Number(n);
  if (!Number.isFinite(v)) return lo;
  return Math.max(lo, Math.min(hi, v));
}

// 反向 judge：cluster 被上游 LLM 拒掉了，二审判断这次拒得对不对
const REJECTION_JUDGE_PROMPT = (cluster: RejectedCluster, articles: ArticleInfo[]) => `
You are reviewing a news article cluster that the upstream LLM validator
REJECTED with reason "${cluster.rejectionReason}". Your job: decide whether
that rejection was correct, or whether the cluster actually contained a real
story that got missed.

# Verdicts
- CORRECT_REJECTION: the cluster really is unrelated junk / topic-too-broad /
  too-few-related items. Rejection was right.
- DEBATABLE: the cluster is borderline — could legitimately be either rejected
  as noise or accepted as a thin/thematic story.
- MISSED_STORY: the cluster contains 2+ articles that DO cover the same
  concrete event/situation. The validator wrongly threw away a real story.

# Rejection reasons recap
- PURE_NOISE: articles unrelated, no shared narrative
- NO_STORIES: cluster too thematic / no concrete shared event
- INSUFFICIENT_ARTICLES: too few articles in cluster to form a story

# Articles (${articles.length})
${articles.map(a => `- [${a.id}] ${a.title}${a.event_summary_points?.length ? '\n    Points: ' + a.event_summary_points.join('; ') : ''}`).join('\n')}

# Output
Reply with ONLY a JSON object inside a \`\`\`json fenced block. No prose.
{
  "verdict": "CORRECT_REJECTION" | "DEBATABLE" | "MISSED_STORY",
  "reason": "<one short sentence>"
}
`.trim();

export async function judgeRejected(
  cluster: RejectedCluster,
  articles: ArticleInfo[],
  options: { model?: string } = {}
): Promise<RejectionJudgeResult> {
  const model = options.model || 'qwen-plus';
  const body = {
    messages: [{ role: 'user', content: REJECTION_JUDGE_PROMPT(cluster, articles) }],
    // skipCache: eval 判官须独立采样，绕开 Gateway 默认缓存（重问逐字复读=样本量退化成 1）
    options: { provider: 'dashscope', model, temperature: 0, max_tokens: 200, skipCache: true },
  };
  const resp = await fetch(`${AI_WORKER_URL}/meridian/chat`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  if (!resp.ok) {
    const txt = await resp.text();
    throw new Error(`Rejection-judge call failed: ${resp.status} ${txt.slice(0, 200)}`);
  }
  const data = (await resp.json()) as { data?: { choices?: Array<{ message?: { content?: string } }> } };
  const content = data?.data?.choices?.[0]?.message?.content || '';
  const parsed = parseJSON(content);
  if (!parsed || typeof (parsed as any).verdict !== 'string') {
    return {
      verdict: 'DEBATABLE',
      reason: `rejection-judge JSON parse failed; raw: ${content.slice(0, 120)}`,
    };
  }
  const v = (parsed as any).verdict as string;
  const allowed: RejectionVerdict[] = ['CORRECT_REJECTION', 'DEBATABLE', 'MISSED_STORY'];
  const verdict: RejectionVerdict = (allowed as string[]).includes(v) ? (v as RejectionVerdict) : 'DEBATABLE';
  return {
    verdict,
    reason: ((parsed as any).reason || '').toString().slice(0, 400),
  };
}

async function judgeStorySinglePass(
  story: Story,
  articles: ArticleInfo[],
  model: string
): Promise<JudgeResult> {
  const body = {
    messages: [{ role: 'user', content: JUDGE_PROMPT(story, articles) }],
    options: { provider: 'dashscope', model, temperature: 0, max_tokens: 300, skipCache: true },
  };

  const resp = await fetch(`${AI_WORKER_URL}/meridian/chat`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  if (!resp.ok) {
    const txt = await resp.text();
    throw new Error(`Judge call failed: ${resp.status} ${txt.slice(0, 200)}`);
  }
  const data = (await resp.json()) as { data?: { choices?: Array<{ message?: { content?: string } }> } };
  const content = data?.data?.choices?.[0]?.message?.content || '';
  const parsed = parseJSON(content);
  if (!parsed) {
    return {
      verdict: 'BORDERLINE',
      coherence: 0,
      title_fit: 0,
      reason: `judge JSON parse failed; raw: ${content.slice(0, 120)}`,
    };
  }
  const v: Verdict = (['REAL', 'BORDERLINE', 'FAKE'] as Verdict[]).includes(parsed.verdict)
    ? parsed.verdict
    : 'BORDERLINE';
  return {
    verdict: v,
    coherence: clamp(parsed.coherence, 1, 5),
    title_fit: clamp(parsed.title_fit, 1, 5),
    reason: (parsed.reason || '').toString().slice(0, 400),
  };
}

// Multi-pass judge：跑 N 次取多数票，缓解 LLM 单次噪声。
// passes=1 时行为与之前完全等价。
export async function judgeStory(
  story: Story,
  articles: ArticleInfo[],
  options: { model?: string; passes?: number } = {}
): Promise<JudgeResult> {
  const model = options.model || 'qwen-plus';
  const passes = Math.max(1, options.passes || 1);

  if (passes === 1) {
    return judgeStorySinglePass(story, articles, model);
  }

  // 并行跑 N 次
  const results = await Promise.all(
    Array.from({ length: passes }, () => judgeStorySinglePass(story, articles, model))
  );

  // 多数票
  const votes = results.map((r) => r.verdict);
  const counts: Record<Verdict, number> = { REAL: 0, BORDERLINE: 0, FAKE: 0 };
  for (const v of votes) counts[v]++;
  const winner = (Object.keys(counts) as Verdict[]).reduce((a, b) =>
    counts[a] >= counts[b] ? a : b
  );
  const winnersResults = results.filter((r) => r.verdict === winner);

  // 选 winner 群里 coherence 最高的作为 representative（reason / 数值字段取它的）
  const rep = winnersResults.reduce((a, b) => (a.coherence >= b.coherence ? a : b));
  const agreement = counts[winner] / passes;

  return {
    verdict: winner,
    coherence: rep.coherence,
    title_fit: rep.title_fit,
    reason: rep.reason,
    passes,
    agreement,
    votes,
  };
}
