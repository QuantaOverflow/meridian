/**
 * 簇判定（cluster judge）提示词：一个聚类簇 = 简报里的一条，这一次调用同时回答
 * 「这簇是不是一件事」和「这件事叫什么」。
 *
 * ## 它取代了什么
 *
 * 2026-09-05 起取代 storyline 两段式（命名主线 + 逐篇归类）。前提变了：聚类换成
 * 不降维凝聚（余弦阈值 0.10、最小 3 篇成簇）之后，一簇 ≈ 一件事——两窗人读全覆盖金标
 * 实测簇纯度 0.864/0.913、题材袋率 0.072/0.000（旧的 UMAP+HDBSCAN 是 0.354/0.408 与
 * 0.286/0.273）。簇内已经基本只有一件事，就不需要再让模型去切分了。
 *
 * 顺带把调用量从每期 430+ 次（每篇一次归类）降到约 69 次（每簇一次）。
 *
 * ## 为什么只问「是不是一件事」，不问「该切成几块」
 *
 * 让模型一次划分整簇是已证伪的：91 篇上 12 轮只有 1 轮把 id 分对（漏 7-9 篇还有重复），
 * 三个高档模型同样崩。而逐簇的二分类 + 起名是它做得了的形态。
 *
 * ## 判据为什么写成这样（四个变体两窗全量实测，F1 121 簇 / F2 152 簇）
 *
 *   变体                          F2 误杀率  F2 题材袋召回   F1 误杀率  F1 题材袋召回
 *   base（只有前三条判据）           4.8%       0.41          8.3%       0.42
 *   把判据改写成「时间+地点+参与者+动作」四要素合取
 *                                  13.6%      0.74         16.5%       0.58
 *   base + 下面的「外延条款」        2.4%       0.33          6.4%       0.42
 *   再加「拿不准偏 EVENT」           0.0%       0.11          0.9%       0.08
 *
 * 三条结论：
 *  · 四要素合取**方向是反的**：模型把它读成更严的检验，两窗一致地把误杀翻 2-3 倍
 *  · 「拿不准偏 EVENT」等于把功能关掉：题材袋召回塌到 0.11/0.08
 *  · 外延条款是唯一两窗同向变好的，且在 F1 上严格优于 base（同召回、精度更高、误杀更低）
 *
 * ⚠️ 判据必须保持**事件无关**：不得出现具体事件的专有词。写死案例既不泛化，又会让离线
 * 评估虚高——本轮调 prompt 时先写了一版把失败样本（某次大火的伤亡数字、某人薪酬与某公司
 * 营收）逐条抄进去，那等于把测试集答案喂进去，已全部删除，只留机制级表述。
 * 端点有运行时断言，指令段含事件专有词即拒。
 *
 * ⚠️ 「拿不准」这一档必须留着，且**必须与调用失败分开**：让模型拒绝整簇 = 簇级硬门的
 * LLM 版，全有全无。零 LLM 的硬门就这么把 8 篇的 NASA 望远镜簇、11 篇的阿富汗驱逐簇
 * 整个抹掉过。调用失败伪装成「没有故事」也在这个仓库骗过一整轮。
 */

import type { JudgeArticle } from '@meridian/contracts';

/**
 * 泛化断言用的正则：指令段里不许出现具体事件的专有词。
 * 从 prompts/storyline.ts 搬过来的（那一层已随判定层上线删除），断言本身仍然有效：
 * 写死案例既不泛化，又会让离线评估虚高——2026-09-03 就被这么骗过一次。
 */
export const EVENT_SPECIFIC_LEAK =
  /\b(nepal|tibet|glacier|glacial|flood|rescue|missing persons|casualt\w*|hurricane|earthquake|wildfire)\b/i;

/** 数据块起始标记。断言只扫这之前的指令段。 */
export const JUDGE_DATA_BLOCK_MARK = '\n报道：\n';

export function getClusterJudgePrompt(articles: JudgeArticle[]): string {
  return `你在给一份新闻简报做选题。下面是聚类算法归到一组的若干篇报道（只给标题，没有正文）。

判断这一组是不是在讲**同一件具体发生的事**（same happening），而不是同一个题材下的若干件不相干的事。

判据：
- 同一件事：同一时间地点发生的同一个事件及其直接组成部分/直接后续（伤亡更新、救援、官方处置、当事方正式回应都算）
- 不是同一件事：只共享题材、地域、人物或赛事名（例：两场不同的枪击案；同一项赛事下的不同比赛；同一个国家的不同社会新闻）
- 就事件本身写的分析、评论、机制解读，算同一件事

「同一件事」的外延按下面这样理解，不要读得过窄：
- 同一件事的不同侧面算同一件事：不同受影响群体各自的处境、不同当事方各自的遭遇、不同地点受到的连带影响与波及
- 同一件事的不同阶段算同一件事：起因、经过、结果，先后阶段的性质可以完全相反，仍属同一件事
- 围绕这件事的各方回应、反驳、追问、辩护，以及由此直接引发的交锋，算同一件事
- 一个人去世本身就是一件事：讣告、生平与作品回顾、悼念、各界反应、影响评价，都属于这一件事
- 续报中伤亡人数、损失规模与事实细节会被不断修正，先后两篇的数字对不上是续报的常态，属于同一件事的特征而不是反证

输出 JSON，不要任何其他文字：
{
  "verdict": "EVENT" | "NO_EVENT" | "UNSURE",
  "title": "这条在简报里的名字，**用英文写**，落在具体的人/地/机构上，不超过 10 个英文词（NO_EVENT 时留空）",
  "event": "一句话说清这件事是什么，**用英文写**（NO_EVENT 时留空）",
  "reason": "一句话理由"
}

说明：
- verdict=EVENT 表示这组确实是一件事
- verdict=NO_EVENT 表示这组只是同题材的一堆不同的事，整组不该成为简报里的一条
- 信息不足以判断时给 UNSURE，不要硬猜
- title 是给读者看的格名，不要写成「关于……的报道」这类空话；event 是给下游写作层的上下文
- **title 与 event 必须是英文**：简报正文是英文的，这两个字段直接进成品（title 就是读者看到的条目名）。
  中文来源的报道也照样用英文写，人名地名用通行英文写法。reason 用中文写没关系，它只进日志。
${JUDGE_DATA_BLOCK_MARK}${articles.map(a => `[${a.id}] ${a.title}`).join('\n')}`;
}
